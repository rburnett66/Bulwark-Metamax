#!/usr/bin/env python3
"""extract_contact.py — regenerate content/dialog/contact.json from the Unknown Contact dialog doc.

Source of truth: docs/16 Bulwark MM/design/Unknown-Contact-Dialog.md [MM-story_mvajkyq5_z].
Same rule as tools/extract_dialog.py: the doc is canonical, the JSON is generated. Re-run after
every doc edit (src/comm/contact.test.mjs fails if they drift):

    python tools/extract_contact.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "..", "..", "..", "docs", "16 Bulwark MM", "design", "Unknown-Contact-Dialog.md")
OUT = os.path.join(HERE, "..", "content", "dialog", "contact.json")


def infer_intent(line):   # same rule as extract_dialog.py
    s = line.rstrip('"” ')
    if s.endswith("!"): return "exclaim"
    if s.endswith("…") or s.endswith("..."): return "trail"
    if s.endswith("?"): return "question"
    return "statement"


text = open(SRC, encoding="utf-8").read()
field = lambda label: (re.search(r"^\*\*" + label + r":\*\* (.+)$", text, re.M) or sys.exit(f"missing **{label}:**"))[1].strip()
section = None
out = {"favour": {}, "replies": {}}
for raw in text.splitlines():
    line = raw.strip()
    if line.startswith("## "):
        section = {"## Favour lines": "favour", "## Replies": "replies"}.get(line)
        continue
    m = re.match(r'^- \*(\w+):\*\s*"(.+)"$', line)
    if m and section:
        out[section][m[1]] = {"line": m[2], "intent": infer_intent(m[2])}

if len(out["favour"]) != 9: sys.exit(f"{len(out['favour'])} favour lines (expected 9)")
for k in ("accept", "decline"):
    if k not in out["replies"]: sys.exit(f"missing reply: {k}")

data = {
    "source": "docs/16 Bulwark MM/design/Unknown-Contact-Dialog.md",
    "docVersion": field("Version").split(" ")[0],
    "note": "GENERATED by tools/extract_contact.py — edit the design doc, not this file.",
    "speaker": {"name": field("Speaker"), "sub": field("Sub"), "gender": field("Gender")},
    **out,
}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump(data, f, indent=1, ensure_ascii=False)
    f.write("\n")
print(f"OK: {len(out['favour'])} favour lines, {len(out['replies'])} replies -> {os.path.normpath(OUT)}")
