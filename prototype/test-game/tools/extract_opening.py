#!/usr/bin/env python3
"""extract_opening.py — regenerate content/dialog/opening.json from the Collective opening dialog doc.
Source of truth: docs/16 Bulwark MM/design/Collective-Opening-Dialog.md [MM-story_mw548j4g_v].
Same rule as tools/extract_contact.py and tools/extract_dialog.py: the doc is canonical, the JSON is generated.
Re-run after every doc edit (src/comm/opening.test.mjs fails if they drift):
    python prototype/test-game/tools/extract_opening.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "..", "..", "..", "docs", "16 Bulwark MM", "design", "Collective-Opening-Dialog.md")
OUT = os.path.join(HERE, "..", "content", "dialog", "opening.json")


def infer_intent(line):   # same rule as extract_dialog.py / extract_contact.py
    s = line.rstrip('"” ')
    if s.endswith("!"): return "exclaim"
    if s.endswith("…") or s.endswith("..."): return "trail"
    if s.endswith("?"): return "question"
    return "statement"


text = open(SRC, encoding="utf-8").read()
field = lambda label: (re.search(r"^\*\*" + label + r":\*\* (.+)$", text, re.M) or sys.exit(f"missing **{label}:**"))[1].strip()
section, slides, lines = None, {}, []
for raw in text.splitlines():
    line = raw.strip()
    if line.startswith("## "):
        section = {"## Slides": "slides", "## Lines": "lines"}.get(line)
        continue
    if section == "slides":
        m = re.match(r"^- \*(\w+):\* (.+?) — (.+)$", line)
        if m: slides[m[1]] = {"title": m[2], "caption": m[3]}
    elif section == "lines":
        m = re.match(r'^- (?:\*(\w+):\* )?"(.+)"$', line)
        if m:
            entry = {"line": m[2], "intent": infer_intent(m[2])}
            if m[1]: entry["slide"] = m[1]
            lines.append(entry)

if not 12 <= len(lines) <= 16: sys.exit(f"{len(lines)} lines (expected 12-16)")
for l in lines:
    if l.get("slide") and l["slide"] not in slides: sys.exit(f"unknown slide: {l['slide']}")

data = {
    "source": "docs/16 Bulwark MM/design/Collective-Opening-Dialog.md",
    "docVersion": field("Version").split(" ")[0],
    "note": "GENERATED by tools/extract_opening.py — edit the design doc, not this file.",
    "speaker": {"name": field("Speaker"), "sub": field("Sub"), "gender": field("Gender")},
    "slides": slides,
    "lines": lines,
}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump(data, f, indent=1, ensure_ascii=False)
    f.write("\n")
print(f"OK: {len(lines)} lines, {len(slides)} slides -> {os.path.normpath(OUT)}")
