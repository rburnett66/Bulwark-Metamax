#!/usr/bin/env node
/**
 * tools/dialog/character_gate.mjs — the CHARACTER SYSTEM report [MM-story_mwp61a5f_32].
 *
 * Builds the generated character model (prototype/test-game/src/data/characterModel.js) from today's content and
 * lists everything the characters fail (src/data/characterGate.js), with every character's generated personality,
 * flaws and circle, for the cast rework (MM-story_mwohmp8n_30).
 *
 * Writes:
 *   docs/16 Bulwark MM/create/Character-Gate-Report.md
 *   prototype/test-game/content/characters/gate-baseline.json   (only with --write-baseline)
 *
 * The baseline is the list of findings the suite tolerates for now (characterSystem.test.mjs): a NEW finding fails
 * the suite, and so does a baseline entry that no longer happens. After fixing content, re-run with
 * --write-baseline so the fixed entries come off the list.
 *
 * Run from the repo root:  node tools/dialog/character_gate.mjs [--write-baseline]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(HERE, '..', '..');
const GAME = path.join(REPO, 'prototype', 'test-game');
const url = (p) => new URL('file:///' + path.join(GAME, p).replace(/\\/g, '/'));
const { buildModel } = await import(url('src/data/characterModel.js'));
const { characterFindings, statRanks } = await import(url('src/data/characterGate.js'));
const { FACTION_KEYS } = await import(url('src/data/factionRelations.js'));
const { HOME_SIDE, MAGICS } = await import(url('src/data/magic.js'));
const { FACTION_TRAITS } = await import(url('src/data/factionTraits.js'));
const { UNITS } = await import(url('src/data/tables.js'));

const json = (p) => JSON.parse(readFileSync(path.join(GAME, p), 'utf8'));
const packs = json('content/dialog/voicepacks.json');
const threads = json('content/characters/threads.json');
const files = {};
for (const k of FACTION_KEYS) if (existsSync(path.join(GAME, `content/characters/${k}.json`))) files[k] = json(`content/characters/${k}.json`);

const model = buildModel({ packs, files, threads });
const ranks = statRanks(UNITS, packs);
const findings = characterFindings(model, files, ranks);

const byCheck = {};
for (const f of findings) (byCheck[f.check] || (byCheck[f.check] = [])).push(f);
const CHECK_TITLE = { files: 'Characters files', personality: 'Personality outside the table (Character-System §4)', love: 'Loves without a thread (§5)',
  hate: 'Hates that name no one (§5)', knowers: 'Secrets no one is in a position to know (§6)', twist: 'Secrets an evil enemy can tell, with no twist (§7.2)',
  secondary: 'Secondaries who know nothing about the map character (§9 check 8)', traits: 'Faction traits (§2a)', magic: 'Magic tags and magic hearts (Magic-System §6.1, §9)' };

const md = [];
md.push('# Character gate report\n');
md.push('Generated by `node tools/dialog/character_gate.mjs` from today\'s content [MM-story_mwp61a5f_32]. The rules are ' +
  '`docs/tech-plan/Character-System.md` and `docs/tech-plan/Magic-System.md`; the model is ' +
  '`prototype/test-game/src/data/characterModel.js`. This is the work list for the cast rework (MM-story_mwohmp8n_30).\n');
md.push(`**${findings.length} findings** across ${Object.keys(byCheck).length} checks. The suite tolerates the ones in ` +
  '`content/characters/gate-baseline.json`; a new finding fails it, and a fixed one has to come off the list ' +
  '(re-run with `--write-baseline`).\n');
md.push('| Check | Findings |\n|---|---|');
for (const [k, list] of Object.entries(byCheck)) md.push(`| ${CHECK_TITLE[k] || k} | ${list.length} |`);
for (const [k, list] of Object.entries(byCheck)) {
  md.push(`\n## ${CHECK_TITLE[k] || k}\n`);
  for (const f of list) md.push(`- ${f.who ? `**${f.who}** (${f.faction}): ` : `**${f.faction}**: `}${f.text}`);
}

md.push('\n## Faction traits against the unit data\n');
md.push('Average level-1 unit stats per faction (`src/data/tables.js` UNITS) and the rank among the nine (1 = highest).\n');
md.push('| Faction | HP | DPS | Range | Speed | Cost | Known for | Known to lack |\n|---|---|---|---|---|---|---|---|');
for (const k of FACTION_KEYS) {
  const a = ranks.avg[k], r = ranks.rank[k], t = FACTION_TRAITS[k];
  if (!a) continue;
  const cell = (s, d = 0) => `${a[s].toFixed(d)} (${r[s]})`;
  md.push(`| ${packs.factions[k].name} | ${cell('hp')} | ${cell('dps', 1)} | ${cell('range', 2)} | ${cell('speed', 2)} | ${cell('cost')} | ` +
    `${t.knownFor.map((w) => w.word).join(' · ')} | ${t.knownToLack.map((w) => w.word).join(' · ')} |`);
}

md.push('\n## Every character, as the rules generate them\n');
md.push('Personality: the declared one when it is the alignment\'s primary or alternate, else the primary (marked ⚠). ' +
  'Flaws: Character-System §5a. Circle: who knows their close secrets.\n');
for (const k of FACTION_KEYS) {
  const fac = packs.factions[k];
  if (!fac) continue;
  md.push(`\n### ${fac.name} · home magic ${MAGICS[HOME_SIDE[k]].faculty}\n`);
  md.push('| Character | Align | Personality | Flaws | Circle |\n|---|---|---|---|---|');
  for (const pc of fac.characters) {
    const p = model.personalityOf(pc.name);
    const flaws = model.flawsOf(pc.name).map((f) => f.word).join(', ') || '—';
    const circle = model.circleOf(pc.name).map((n) => n.replace(/^\S+ /, '')).join(', ') || '—';
    md.push(`| ${pc.name} | ${pc.align} | ${p.personality}${p.outside ? ` ⚠ (was ${p.declared})` : ''} | ${flaws} | ${circle} |`);
  }
}

const flawCount = {};
for (const n of model.chars.keys()) for (const f of model.flawsOf(n)) flawCount[f.word] = (flawCount[f.word] || 0) + 1;
md.push('\n## Flaw spread\n');
md.push('How often each flaw word comes out across the 81. A word far more common than the rest means the rules lean one ' +
  'way and may want tuning.\n');
md.push(Object.entries(flawCount).sort((a, b) => b[1] - a[1]).map(([w, n]) => `${w} ${n}`).join(' · '));
md.push(`\n\nNo flaw: ${[...model.chars.keys()].filter((n) => !model.flawsOf(n).length).length} characters.`);

writeFileSync(path.join(REPO, 'docs', '16 Bulwark MM', 'create', 'Character-Gate-Report.md'), md.join('\n') + '\n');
if (process.argv.includes('--write-baseline')) {
  writeFileSync(path.join(GAME, 'content', 'characters', 'gate-baseline.json'), JSON.stringify({
    _source: 'Findings the suite tolerates for now (src/data/characterGate.js). Written by tools/dialog/character_gate.mjs --write-baseline; do not add to it by hand. Fix content, then re-run so the fixed entries come off.',
    findings: findings.map((f) => f.id),
  }, null, 1) + '\n');
}
console.log(`${findings.length} findings; ${Object.entries(byCheck).map(([k, l]) => `${k} ${l.length}`).join(', ')}`);
